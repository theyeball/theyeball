# module
# essentially just a .py file with functionality (functions, classes, etc.)
# e.g. random, datetime

# package
# contains multiple multiple modules

# library
# contains multiple modules and packages
# e.g. matplotlib


# how to import

# you can import a singular module by using 
'''import module1'''

# same thing with packages and libraries
'''import package1'''
'''import library1'''

# you may also wish to import a single module from a package
'''from package1 import module1'''

# or maybe a single function/class from a module
'''from module1 import function1'''

# if you want to try to extract something from nested modules and packages, you can choose subcategories by using dots
'''from library1.package1 import module1'''
'''from library1.package1.module1 import functio1'''